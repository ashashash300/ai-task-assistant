from collections.abc import Sequence
from typing import Any

from google.genai import types


GEMINI_HISTORY_SCHEMA_VERSION = 1


class ConversationCodecError(Exception):
    """Raised when persisted Gemini conversation state cannot be safely restored."""


def _function_calls(content: types.Content) -> list[Any]:
    return [
        part.function_call
        for part in (content.parts or [])
        if part.function_call is not None
    ]


def _function_responses(content: types.Content) -> list[Any]:
    return [
        part.function_response
        for part in (content.parts or [])
        if part.function_response is not None
    ]


def _validate_history_structure(history: Sequence[types.Content]) -> None:
    """Validate the user/model pattern generated by the current Gemini provider."""

    if not history:
        return

    for index, content in enumerate(history):
        calls = _function_calls(content)
        responses = _function_responses(content)

        if content.role not in {"user", "model"}:
            raise ConversationCodecError("Gemini conversation history is invalid")
        if index == 0 and (content.role != "user" or responses):
            raise ConversationCodecError("Gemini conversation history is invalid")
        if calls and responses:
            raise ConversationCodecError("Gemini conversation history is invalid")

        if calls:
            if content.role != "model" or index + 1 >= len(history):
                raise ConversationCodecError("Gemini conversation history is invalid")
            next_content = history[index + 1]
            next_responses = _function_responses(next_content)
            if next_content.role != "user" or not next_responses:
                raise ConversationCodecError("Gemini conversation history is invalid")
            if [call.name for call in calls] != [response.name for response in next_responses]:
                raise ConversationCodecError("Gemini conversation history is invalid")

        if responses:
            if content.role != "user" or index == 0:
                raise ConversationCodecError("Gemini conversation history is invalid")
            if not _function_calls(history[index - 1]):
                raise ConversationCodecError("Gemini conversation history is invalid")

    if history[-1].role != "model" or _function_calls(history[-1]):
        raise ConversationCodecError("Gemini conversation history is incomplete")


def encode_gemini_history(history: list[types.Content]) -> dict[str, Any]:
    """Encode validated Gemini Content objects as JSON-compatible persisted state."""

    if not isinstance(history, list) or not all(
        isinstance(content, types.Content) for content in history
    ):
        raise ConversationCodecError("Gemini conversation history is invalid")

    _validate_history_structure(history)
    try:
        contents = [
            content.model_dump(mode="json", exclude_none=True) for content in history
        ]
    except Exception as error:
        raise ConversationCodecError("Gemini conversation history cannot be encoded") from error

    return {
        "schema_version": GEMINI_HISTORY_SCHEMA_VERSION,
        "contents": contents,
    }


def decode_gemini_history(payload: object) -> list[types.Content]:
    """Restore validated Gemini Content objects without exposing persisted content in errors."""

    if not isinstance(payload, dict):
        raise ConversationCodecError("Gemini conversation history is invalid")

    schema_version = payload.get("schema_version")
    if schema_version != GEMINI_HISTORY_SCHEMA_VERSION or isinstance(schema_version, bool):
        raise ConversationCodecError("Unsupported Gemini history schema version")

    raw_contents = payload.get("contents")
    if not isinstance(raw_contents, list) or not all(
        isinstance(content, dict) for content in raw_contents
    ):
        raise ConversationCodecError("Gemini conversation history is invalid")

    try:
        history = [types.Content.model_validate(content) for content in raw_contents]
    except Exception as error:
        raise ConversationCodecError("Gemini conversation history is invalid") from error

    _validate_history_structure(history)
    return history
